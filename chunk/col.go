package chunk

import (
	"github.com/helix-bedrock/world/cube"
)

// Column is a chunk with everything saved alongside it: entities, block
// entities, its tick and pending scheduled block updates.
type Column struct {
	Chunk           *Chunk
	Entities        []Entity
	BlockEntities   []BlockEntity
	Tick            int64
	ScheduledBlocks []ScheduledBlockUpdate
	// Finalisation is the chunk's generation state, saved as is. Use
	// DefaultFinalisation for a finished chunk.
	Finalisation Finalisation
	// MetaDataHash points into the world's chunk metadata dictionary. Zero
	// means a chunk generated by this server, which gets current metadata
	// when it is saved.
	MetaDataHash uint64
	// BlendingData is the chunk's raw blending data, written back as is.
	// Nil for a chunk generated by this server.
	BlendingData []byte
}

// Finalisation is how far a chunk got through world generation. The values
// are the ones Bedrock stores.
type Finalisation int32

const (
	// FinalisationNeedsTicking means generated, not yet ticked.
	FinalisationNeedsTicking Finalisation = iota
	// FinalisationNeedsPopulation means generated, features not yet placed.
	FinalisationNeedsPopulation
	// FinalisationDone means fully generated, the state nearly every saved
	// chunk holds.
	FinalisationDone
)

// DefaultFinalisation returns the state of a fully generated chunk. It is
// also what Bedrock assumes when a chunk has no state saved.
func DefaultFinalisation() Finalisation {
	return FinalisationDone
}

// BlockEntity is the saved NBT data of a block entity at Pos.
type BlockEntity struct {
	Pos  cube.Pos
	Data map[string]any
}

// Entity is the saved NBT data of an entity with its unique ID.
type Entity struct {
	ID   int64
	Data map[string]any
}

// ScheduledBlockUpdate is a block update due at Tick for the block at Pos.
type ScheduledBlockUpdate struct {
	Pos   cube.Pos
	Block uint32
	Tick  int64
}
